  PASSWORD_NOT_MATCH: 10006,
  USER_NOT_FOUND: 10007,
  PERMISSION_DENIED: 10008,
  DATA_SCOPE_DENIED: 10009,
  TOO_MANY_REQUESTS: 10010,
  IDEMPOTENT_CONFLICT: 10011,
